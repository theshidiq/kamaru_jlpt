export type I18nKey = keyof typeof strings.en

export function t(
  key: I18nKey,
  lang: 'id' | 'en',
  vars?: Record<string, string | number>,
): string {
  const raw = strings[lang]?.[key] ?? strings.en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, k) => String(vars[k] ?? m))
}
